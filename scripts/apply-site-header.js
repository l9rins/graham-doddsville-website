#!/usr/bin/env node
// Apply the shared subpage header, drawer and back-link convention to every
// subpage in public/. Re-runnable: pages already converted are rebuilt from
// the same canonical markup, so the drawer menu can be changed here once.
//
// Usage: node scripts/apply-site-header.js [--dry-run]

const fs = require('fs');
const path = require('path');

const PUBLIC = path.join(__dirname, '..', 'public');
const DRY_RUN = process.argv.includes('--dry-run');

// Pages that are not subpages or are orphaned/broken (see BACKLOG.md)
const SKIP = new Set(['index.html', 'news-articles.html', 'warren-buffett-economics-backup.html']);

// Same menu as the homepage drawer
const MENU = [
    ['index.html', 'Home'],
    ['wealth-creation.html', 'Wealth Creation'],
    ['legal-taxation.html', 'Legal &amp; Taxation'],
    ['financial-markets.html', 'Financial Markets'],
    ['share-investing.html', 'Share Investing'],
    ['Greatest-Investors.html', 'Greatest Investors'],
    ['investment-analysis.html', 'Investment Analysis'],
    ['financial-statement-analysis.html', 'Financial Statement Analysis'],
    ['stock-valuation.html', 'Stock Valuation'],
    ['sidebar-economics.html', 'Economics'],
    ['professional-advisers.html', 'Professional Advisers'],
    ['financial-products.html', 'Financial Products'],
    ['resources.html', 'Resources'],
    ['events.html', 'Events &amp; Seminars'],
    ['about-us.html', 'About Us']
];

const ICON = id => `<svg class="icon" aria-hidden="true"><use href="images/icons.svg#${id}"></use></svg>`;

const HEADER = `<!-- Site header (shared; generated by scripts/apply-site-header.js) -->
    <header class="header sticky-header site-header" role="banner">
        <div class="container">
            <div class="header-content">
                <a href="index.html" class="logo" aria-label="Graham and Doddsville home">
                    <img src="images/gd-logo-dark.png" alt="Graham and Doddsville" class="logo-image">
                </a>
                <button class="mobile-menu-toggle" id="mobile-toggle" type="button" aria-label="Open menu" aria-controls="mobile-drawer" aria-expanded="false">
                    <span class="hamburger-line"></span>
                    <span class="hamburger-line"></span>
                    <span class="hamburger-line"></span>
                </button>
            </div>
        </div>
    </header>
    <div class="mobile-drawer site-drawer" id="mobile-drawer">
        <div class="drawer-header">
            <img src="images/gd-logo-dark.png" alt="" class="drawer-logo">
            <button class="drawer-close" id="drawer-close" type="button" aria-label="Close menu">${ICON('icon-close')}</button>
        </div>
        <nav class="drawer-nav" aria-label="Site">
            <ul class="drawer-menu">
${MENU.map(([href, label]) => `                <li><a href="${href}" class="drawer-link">${label}</a></li>`).join('\n')}
            </ul>
        </nav>
    </div>
    <!-- /Site header -->`;

const HEADER_BLOCK = /<!-- Site header \(shared[\s\S]*?<!-- \/Site header -->/;

// Remove an element starting at `start` (index of its opening tag), matching nested tags of the same name
function removeElement(html, start, tag) {
    const re = new RegExp(`<${tag}\\b|</${tag}>`, 'gi');
    re.lastIndex = start;
    let depth = 0, m;
    while ((m = re.exec(html))) {
        depth += m[0][1] === '/' ? -1 : 1;
        if (depth === 0) return { html: html.slice(0, start) + html.slice(re.lastIndex), removed: html.slice(start, re.lastIndex) };
    }
    throw new Error(`unbalanced <${tag}>`);
}

function backLabel(text) {
    const label = text.replace(/[←‹«]/g, '').replace(/^\s*back to\s*/i, '').replace(/\s+/g, ' ').trim();
    if (!label) return 'Back';
    return /^home$/i.test(label) ? 'Home' : label;
}

// Old back-link conventions: .breadcrumb-link, .breadcrumb (anchor), .back-btn
function convertBackLinks(html) {
    let count = 0;
    html = html.replace(/<a\b([^>]*)class="(breadcrumb-link|breadcrumb|back-btn)"([^>]*)>([\s\S]*?)<\/a>/g, (all, pre, cls, post, inner) => {
        const text = inner.replace(/<[^>]+>/g, ' ');
        if (!/[←‹«]|back|home/i.test(text)) return all;
        count++;
        return `<a${pre}class="back-link"${post}>${ICON('icon-arrow-left')}<span>${backLabel(text)}</span></a>`;
    });
    return { html, count };
}

const report = [];
for (const file of fs.readdirSync(PUBLIC).filter(f => f.endsWith('.html') && !SKIP.has(f)).sort()) {
    const full = path.join(PUBLIC, file);
    let html = fs.readFileSync(full, 'utf8');
    const original = html;
    const notes = [];
    let movedBackLink = null;

    const alreadyConverted = HEADER_BLOCK.test(html);
    if (alreadyConverted) {
        // Re-run: refresh the shared block in place
        html = html.replace(HEADER_BLOCK, HEADER);
    } else {
        // Old site header: a <header> whose class list includes "header"
        const hm = /<header\b[^>]*class="(?:[^"]*\s)?header(?:\s[^"]*)?"[^>]*>/.exec(html);
        if (hm) {
            const r = removeElement(html, hm.index, 'header');
            html = r.html;
            const back = /<a\b[^>]*class="(?:breadcrumb-link|breadcrumb|back-btn)"[^>]*>[\s\S]*?<\/a>/.exec(r.removed);
            if (back) movedBackLink = back[0];
            notes.push('old header removed' + (back ? ' (back link moved)' : ''));
        } else {
            notes.push('no old site header');
        }
        const dm = /<div\b[^>]*id="mobile-drawer"[^>]*>/.exec(html);
        if (dm) {
            html = removeElement(html, dm.index, 'div').html;
            notes.push('old drawer removed');
        }
    }

    // Insert the shared header straight after <body>
    if (!alreadyConverted) html = html.replace(/(<body\b[^>]*>)/, `$1\n    ${HEADER}\n`);

    // A back link that lived in the old header goes to the top of the page title section
    if (movedBackLink) {
        const target = /<div\b[^>]*class="[^"]*\bpage-title-section\b[^"]*"[^>]*>/.exec(html) || /<main\b[^>]*>/.exec(html);
        if (!target) throw new Error(`${file}: nowhere to put the back link`);
        const at = target.index + target[0].length;
        html = html.slice(0, at) + `\n                <div class="breadcrumb">${movedBackLink}</div>` + html.slice(at);
    }

    const back = convertBackLinks(html);
    html = back.html;
    notes.push(`${back.count} back link(s)`);

    if (!html.includes('css/site-header.css')) {
        html = html.replace('</head>', '    <link rel="stylesheet" href="css/site-header.css">\n</head>');
    }
    if (!html.includes('js/site-nav.js')) {
        const i = html.lastIndexOf('</body>');
        html = html.slice(0, i) + '    <script src="js/site-nav.js" defer></script>\n' + html.slice(i);
    }

    if (html !== original && !DRY_RUN) fs.writeFileSync(full, html);
    report.push(`${file.padEnd(36)} ${notes.join('; ')}`);
}
console.log(report.join('\n'));
console.log(`${report.length} pages${DRY_RUN ? ' (dry run)' : ''}`);
